(async () => {
  const checks = [];
  const assert = (value, name) => { if (!value) throw new Error(name); checks.push(name); };
  const until = async predicate => {
    const deadline = Date.now() + 6000;
    while (!predicate()) {
      if (Date.now() > deadline) throw new Error("Timed out waiting for diagnostics");
      await new Promise(resolve => setTimeout(resolve, 30));
    }
  };
  const tick = () => new Promise(resolve => setTimeout(resolve, 50));
  history.replaceState(null, "", "/artist_one/media?filter=photo");
  document.querySelector("#timeline").innerHTML = [900, 899].map(id => `<a href="https://x.com/artist_one/status/${id}/photo/1" style="display:block;height:80px">Photo ${id}</a>`).join("");
  document.querySelector("h1").setAttribute("data-testid", "UserName");
  document.querySelector("h1").append(" diagnostics");
  window.scrollTo(0, 0);
  await until(() => document.querySelector("#xis-author-download"));
  const panel = document.querySelector("#xis-author-download");
  const [start, fast, stop] = panel.querySelectorAll("button");
  const status = panel.querySelector('[role="status"]');
  const details = panel.querySelector(".xis-error-detail");
  const downloads = () => fixture.calls.filter(call => call.type === "XIS_DOWNLOAD_POST");
  const metadata = id => ({ author: "artist_one", postId: String(id), images: [`https://pbs.twimg.com/media/Diagnostic${id}.jpg`] });
  const diagnostic = (requestId, extra = {}) => window.postMessage({ type: "XIS_TIMELINE_STATUS", path: location.pathname, search: location.search, requestId, requestedAt: Date.now(), observedAt: Date.now(), ended: false, error: null, reason: "ok", ...extra }, location.origin);
  window.postMessage({ type: "XIS_PHOTO_DATA", items: [metadata(900), metadata(899)] }, location.origin);
  await tick();
  fixture.statusMode = "pending";
  start.click();
  await until(() => fixture.statusPolls > 0);
  diagnostic(1, { search: "", reason: "rate-limit", error: "Wrong filter HTTP 429" });
  await tick();
  assert(start.disabled && !details.textContent, "Another media filter cannot interrupt the current task");
  diagnostic(3);
  diagnostic(2, { reason: "rate-limit", error: "X 媒体列表已限流（HTTP 429）。", retryAt: Date.now() + 300000 });
  diagnostic(3);
  await tick();
  assert(start.disabled && downloads().length === 1, "A timeline failure waits for the in-flight post without starting the next one");
  fixture.statusMode = "complete";
  await until(() => !start.disabled);
  assert(downloads().length === 1 && status.textContent.includes("保存 1"), "Timeline failure retains completed counts and prevents the next download");
  assert(details.textContent.includes("停止原因") && details.textContent.includes("HTTP 429") && details.textContent.includes("建议在"), "A later success cannot erase the rate-limit reason or suggested retry time");

  fixture.statusMode = "pending";
  start.click();
  await until(() => downloads().length === 2);
  assert(!details.textContent, "A deliberate retry can continue without being trapped by the previous failure");
  diagnostic(4, { ended: true });
  window.postMessage({ type: "XIS_PHOTO_DATA", items: [metadata(898)] }, location.origin);
  fixture.statusMode = "complete";
  await until(() => !start.disabled);
  assert(downloads().slice(1).map(call => call.post.postId).join(",") === "900,899,898", "Explicit termination drains metadata received during an in-flight download");
  assert(status.textContent.includes("明确返回本次媒体时间线末尾") && status.textContent.includes("保存 3"), "Only explicit timeline termination reports the end with final totals");

  diagnostic(5, { reason: "access", error: "X 拒绝访问媒体列表（HTTP 403）。" });
  await tick();
  const beforeIdle = downloads().length;
  start.click();
  await until(() => !start.disabled);
  assert(downloads().length === beforeIdle && details.textContent.includes("HTTP 403"), "A recent failure observed before starting is diagnosed instead of silently waiting");
  fixture.savedPhotoPosts.add("900"); fixture.savedPhotoPosts.add("899"); fixture.savedPhotoPosts.add("898");
  diagnostic(6);
  await tick();
  fast.click();
  await until(() => fixture.calls.some(call => call.type === "XIS_PHOTO_HISTORY"));
  diagnostic(7, { reason: "network", error: "X 媒体列表请求超时。" });
  await until(() => !fast.disabled);
  assert(details.textContent.includes("超时") && status.textContent.includes("已确认保存 3"), "Fast location retains its totals and specific network stop reason");

  const spacer = document.createElement("div");
  spacer.style.height = "1800px"; document.querySelector("main").append(spacer);
  const originalScrollBy = window.scrollBy;
  window.scrollBy = () => {};
  diagnostic(8, { exhausted: true });
  await tick();
  start.click();
  await tick();
  assert(start.disabled && !status.textContent.includes("本次分页没有后续"), "An exhausted cursor observed above the bottom cannot prematurely finish the task");
  const beforeExhausted = Date.now();
  window.scrollTo(0, document.documentElement.scrollHeight);
  await until(() => !start.disabled);
  assert(status.textContent.includes("本次分页没有后续") && status.textContent.includes("不代表全部历史") && Date.now() - beforeExhausted < 2000, "A cursor-exhausted page finishes without the 90-second wait or a claim of complete account history");
  window.scrollBy = originalScrollBy;
  spacer.remove(); window.scrollTo(0, 0);
  diagnostic(9);
  await tick();
  const error = document.createElement("div");
  error.dataset.testid = "error-detail"; error.textContent = "Something went wrong. Try reloading.";
  document.querySelector("main").append(error);
  start.click();
  await until(() => !start.disabled);
  assert(details.textContent.includes("Something went wrong") && details.textContent.includes("无法确认是否为风控"), "Generic X errors retain the page message without falsely claiming rate limiting");
  error.remove();
  assert(stop.hidden, "Diagnostic stops leave the panel ready to continue");
  return { passed: checks.length, checks };
})();
